// Afterimage — hand-designed levels. Every level's `solution` is machine-verified by
// the throwaway harness used during development (see game.js self-test, which replays
// these at runtime) — unsolvable levels are deleted, never shipped.
//
// Grid legend:
//   # solid wall        . empty          ^ spike (deadly)
//   S spawn              G goal           _ one-way ledge (land on top, pass from below)
//   1-6 pressure plate (one-way top; weighted by player OR any visible ghost)
//   a-f door (matches plate 1-6; solid unless its plate is weighted; ghosts always pass through)
//
// games/afterimage/generator.js procedurally builds and machine-verifies levels 4-74
// (a "chain" archetype: 1-6 sequential plate/door segments, escalating corridor length,
// spike density, and elevated one-way-ledge plates). Every level below (hand-designed or
// generated) is re-verified at build time by tools/verify.mjs and at runtime by
// registerSelftest: solution replays to a win AND an 8000-attempt single-life randomized
// search finds zero wins (the door/ghost mechanic is provably required, not decorative).

// A `solution` is an array of runs; each run is an array of [frames, mask] RLE pairs
// (mask bits: 1=left, 2=right, 4=jump). A run that ends without dying or reaching the
// goal is a manual retry — exactly what pressing R does live. Verified by node.js in
// development (see report) and re-verified every load by the in-browser self-test.
